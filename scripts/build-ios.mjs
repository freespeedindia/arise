// Builds the iPhone (Xcode) project in ios/ so it opens and runs on a Mac with only Xcode installed.
//   node scripts/build-ios.mjs            -> refresh ios/ from the current app
//   node scripts/build-ios.mjs --zip DIR  -> also write DIR/Arise-iPhone-<version>.zip
// The plugin code is copied into ios/ (no Node.js or CocoaPods needed on the Mac).
import { execSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'

const run = (c, env = {}) => execSync(c, { stdio: 'inherit', env: { ...process.env, ...env } })
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
process.chdir(root)
const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'))

run('npm run build', { BASE_PATH: '/' })
run('npx cap sync ios')

const spm = 'ios/App/CapApp-SPM'
const manifestPath = `${spm}/Package.swift`
let manifest = fs.readFileSync(manifestPath, 'utf8')
fs.rmSync(`${spm}/Plugins`, { recursive: true, force: true })
manifest = manifest.replace(/\.package\(name: "([^"]+)", path: "\.\.\/\.\.\/\.\.\/node_modules\/([^"]+)"\)/g, (_m, name, mod) => {
  const src = `node_modules/${mod}`
  const dst = `${spm}/Plugins/${name}`
  fs.mkdirSync(`${dst}/ios`, { recursive: true })
  fs.cpSync(`${src}/ios/Sources`, `${dst}/ios/Sources`, { recursive: true })
  for (const f of ['LICENSE']) if (fs.existsSync(`${src}/${f}`)) fs.copyFileSync(`${src}/${f}`, `${dst}/${f}`)
  // Drop the plugin's own test target (its test files are not shipped)
  const pm = fs.readFileSync(`${src}/Package.swift`, 'utf8').replace(/,\s*\.testTarget\([\s\S]*?\)\s*(?=\]\s*\)\s*$)/, '\n    ')
  fs.writeFileSync(`${dst}/Package.swift`, pm)
  return `.package(name: "${name}", path: "Plugins/${name}")`
})
manifest = manifest.replace('// DO NOT MODIFY THIS FILE - managed by Capacitor CLI commands', '// Generated by scripts/build-ios.mjs (plugins copied into Plugins/ so no Node.js is needed on the Mac)')
fs.writeFileSync(manifestPath, manifest)

// Reminders should make the normal iPhone notification sound
const lnp = `${spm}/Plugins/CapacitorLocalNotifications/ios/Sources/LocalNotificationsPlugin/LocalNotificationsPlugin.swift`
if (fs.existsSync(lnp)) {
  const s = fs.readFileSync(lnp, 'utf8')
  const patched = s.replace(
    /if let sound = notification\["sound"\] as\? String \{\n(\s*)content\.sound = UNNotificationSound\(named: UNNotificationSoundName\(sound\)\)\n(\s*)\}/,
    (m, a, b) => `${m} else {\n${a}content.sound = UNNotificationSound.default\n${b}}`)
  if (patched === s) throw new Error('Could not add the notification sound')
  fs.writeFileSync(lnp, patched)
}

// Version shown on the iPhone = package.json version
const pbx = 'ios/App/App.xcodeproj/project.pbxproj'
fs.writeFileSync(pbx, fs.readFileSync(pbx, 'utf8').replace(/MARKETING_VERSION = [^;]+;/g, `MARKETING_VERSION = ${pkg.version};`))
console.log(`\niOS project ready (Arise ${pkg.version}).`)

const zi = process.argv.indexOf('--zip')
if (zi > 0) {
  const out = path.resolve(process.argv[zi + 1])
  fs.mkdirSync(out, { recursive: true })
  const stage = fs.mkdtempSync('/tmp/arise-ios-')
  const top = `${stage}/Arise-iPhone`
  fs.cpSync('ios', `${top}/ios`, { recursive: true, filter: (p) => !/xcuserdata|DerivedData|\/build$|\.DS_Store/.test(p) })
  fs.copyFileSync('IPHONE.md', `${top}/READ ME FIRST.md`)
  const zip = `${out}/Arise-iPhone-${pkg.version}.zip`
  fs.rmSync(zip, { force: true })
  run(`cd "${stage}" && zip -qr -X "${zip}" Arise-iPhone`)
  console.log(`Wrote ${zip}`)
}
