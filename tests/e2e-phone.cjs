  // 6. Dark mode + settings + backup
  await tap('[aria-label="Settings"]'); await wait()
  await tap('[role=dialog] button:has-text("Dark")'); await wait(300)
  const dl = page.waitForEvent('download', { timeout: 5000 }).catch(() => null)
