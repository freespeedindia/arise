  await tap('[role=dialog] button:text-is("Create PDF")'); await wait(2500)
  dl2 = page.waitForEvent('download', { timeout: 8000 }).catch(() => null)
  await tap('[role=dialog] button:has-text("Save to phone")')
  f2 = await dl2
